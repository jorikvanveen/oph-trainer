fn topic(id: &str, name: &str) -> TopicDto {
    TopicDto {
        topic_id: id.into(),
        name: name.into(),
    }
}

fn strings(values: &[&str]) -> Vec<String> {
    values.iter().map(|value| (*value).into()).collect()
}

fn short(
    id: &str,
    topic: &str,
    source: &str,
    prompt: &str,
    reference: &str,
    accepted: &[&str],
    aliases: &[&str],
) -> QuestionDto {
    QuestionDto {
        question_id: id.into(),
        topic_id: topic.into(),
        prompt: prompt.into(),
        reference_answer: reference.into(),
        source_url: source.into(),
        material: vec![],
        grading: AnswerCriteria::ShortAnswer {
            accepted_answers: strings(accepted),
            aliases: strings(aliases),
        },
    }
}

#[allow(clippy::too_many_arguments)]
fn explain(
    id: &str,
    topic: &str,
    source: &str,
    prompt: &str,
    reference: &str,
    required: &[&str],
    optional: &[&str],
    contradictions: &[&str],
) -> QuestionDto {
    QuestionDto {
        question_id: id.into(),
        topic_id: topic.into(),
        prompt: prompt.into(),
        reference_answer: reference.into(),
        source_url: source.into(),
        material: vec![],
        grading: AnswerCriteria::Explanation {
            required_points: strings(required),
            optional_points: strings(optional),
            contradictions: strings(contradictions),
        },
    }
}

